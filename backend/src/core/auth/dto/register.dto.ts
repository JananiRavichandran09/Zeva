import { IsEmail, IsString, MinLength } from 'class-validator';

export class RegisterDto {
  @IsString()
  @MinLength(2)
  name: string;

  @IsEmail()
  email: string;

  @IsString()
  @MinLength(6)
  password: string;

  /** Optional: organization name to bootstrap (creates org + makes user admin) */
  @IsString()
  orgName?: string;
}
